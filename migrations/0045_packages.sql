-- The package catalog (spec section 8). Rows are never updated: a price change inserts the next version, so a proposal that snapshotted version N keeps its price.
CREATE TABLE packages (
  id TEXT PRIMARY KEY,
  key TEXT NOT NULL,
  version INTEGER NOT NULL CHECK (version >= 1),
  name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('one_time', 'monthly', 'subscription', 'hourly')),
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
  setup_cents INTEGER NOT NULL DEFAULT 0 CHECK (setup_cents >= 0),
  term_months INTEGER CHECK (term_months IS NULL OR term_months > 0),
  alt_price_cents INTEGER CHECK (alt_price_cents IS NULL OR alt_price_cents >= 0),
  from_price INTEGER NOT NULL DEFAULT 0 CHECK (from_price IN (0, 1)),
  summary TEXT NOT NULL DEFAULT '',
  includes TEXT NOT NULL DEFAULT '[]',
  wordpress_only INTEGER NOT NULL DEFAULT 0 CHECK (wordpress_only IN (0, 1)),
  public_offer INTEGER NOT NULL DEFAULT 1 CHECK (public_offer IN (0, 1)),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at TEXT NOT NULL,
  UNIQUE (key, version)
);

